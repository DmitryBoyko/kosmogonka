"""Prepare every user Girl take as mono OGG; preserve the supplied voice and duration."""
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import re
import shutil
import subprocess
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path(r"C:\Users\dmitr\Downloads\Girl")
ARCHIVE = ROOT / "docs/audio_sources/user_girl"
OUTPUT = ROOT / "assets/audio"
CATEGORIES = ["jump", "laugh", "joy", "win", "hit", "surprise"]

def prepare(path):
    match = re.fullmatch(r"girl_(jump|laugh|joy|win|hit|surprise)_(\d+)", path.stem)
    assert match, f"Unknown voice category: {path.name}"
    category, variant = match.groups()
    decoded = subprocess.check_output(["ffmpeg", "-nostdin", "-v", "error", "-i", str(path),
                                       "-f", "f32le", "-ac", "1", "-ar", "44100", "pipe:1"])
    pcm = np.frombuffer(decoded, dtype="<f4").copy()
    original_seconds = len(pcm) / 44100
    active = np.flatnonzero(np.abs(pcm) > .001)
    assert active.size, f"Silent recording: {path.name}"
    padding = round(.03 * 44100)
    pcm = pcm[max(0, active[0] - padding):min(len(pcm), active[-1] + 1 + padding)]
    for count, tail in [(round(.005 * 44100), False), (round(.008 * 44100), True)]:
        count = min(count, len(pcm))
        if tail:
            pcm[-count:] *= np.linspace(1, 0, count)
        else:
            pcm[:count] *= np.linspace(0, 1, count)
    rms = float(np.sqrt(np.mean(pcm.astype(np.float64) ** 2)))
    peak = float(np.max(np.abs(pcm)))
    gain = min(10 ** (-22 / 20) / rms, 10 ** (-5 / 20) / peak)
    pcm *= gain
    target = OUTPUT / (path.stem + ".ogg")
    subprocess.run(["ffmpeg", "-nostdin", "-v", "error", "-y", "-f", "f32le", "-ar", "44100", "-ac", "1",
                    "-i", "pipe:0", "-map_metadata", "-1", "-c:a", "libvorbis", "-q:a", "4", str(target)],
                   input=pcm.astype("<f4").tobytes(), check=True)
    if path.resolve() != (ARCHIVE / path.name).resolve():
        shutil.copyfile(path, ARCHIVE / path.name)
    return {"category": category, "variant": int(variant), "source": path.name,
            "source_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
            "output": target.name, "sha256": hashlib.sha256(target.read_bytes()).hexdigest(),
            "source_seconds": original_seconds, "seconds": len(pcm) / 44100,
            "gain_db": float(20 * np.log10(gain)), "bytes": target.stat().st_size}

def main():
    folder = SOURCE if SOURCE.exists() else ARCHIVE
    files = sorted((p for p in folder.iterdir() if p.is_file() and p.suffix.lower() in {".mp3", ".wav", ".ogg", ".m4a", ".flac"}),
                   key=lambda p: (p.stem.split("_")[1], int(p.stem.split("_")[-1])))
    assert files, "No voice files found"
    ARCHIVE.mkdir(parents=True, exist_ok=True)
    with ThreadPoolExecutor(max_workers=3) as workers:
        clips = list(workers.map(prepare, files))
    groups = {category: [Path(c["output"]).stem for c in clips if c["category"] == category] for category in CATEGORIES}
    assert all(groups.values()), "All six reaction categories must be present"
    catalog = "extends RefCounted\n## All user-provided Girl recordings; generated by prepare_girl_voices.py.\nconst GROUPS := {\n"
    for category, names in groups.items():
        catalog += f"\t{json.dumps(category)}: {json.dumps(names)},\n"
    catalog += "}\nconst CLIPS := {\n"
    for clip in clips:
        key = Path(clip["output"]).stem
        catalog += f'\t"{key}": preload("res://assets/audio/{clip["output"]}"),\n'
    catalog += "}\n"
    (OUTPUT / "girl_voices.gd").write_text(catalog, encoding="utf-8")
    manifest = {"source_folder": str(SOURCE), "date": "2026-11-04", "format": "OGG Vorbis q4 / mono / 44.1 kHz",
                "processing": "Trim below -60 dBFS with 30 ms padding; 5/8 ms edge fades; RMS target -22 dBFS capped at -5 dBFS peak; no pitch or tempo changes",
                "counts": {k: len(v) for k, v in groups.items()}, "clips": clips,
                "source_bytes": sum(p.stat().st_size for p in files), "output_bytes": sum(c["bytes"] for c in clips)}
    (ARCHIVE.parent / "user_girl_manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({k: manifest[k] for k in ["counts", "source_bytes", "output_bytes"]}, ensure_ascii=False))

if __name__ == "__main__":
    main()
