"""Prepare user-supplied ArcadaMusic as normalized stereo OGG and a Godot catalog."""
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path(r"C:\Users\dmitr\Downloads\ArcadaMusic")
DEST = ROOT / "assets/music"
DEST.mkdir(exist_ok=True)
files = sorted(p for p in SOURCE.iterdir() if p.suffix.lower() in {".mp3", ".wav", ".ogg", ".flac", ".m4a"})
assert files, "No source music found"

def convert(item):
    index, path = item
    target = DEST / f"arcade_{index:02d}.ogg"
    subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", str(path),
                    "-vn", "-af", "loudnorm=I=-18:TP=-2:LRA=9", "-ar", "44100", "-ac", "2",
                    "-c:a", "libvorbis", "-q:a", "4", str(target)], check=True)
    probe = json.loads(subprocess.check_output(["ffprobe", "-v", "error", "-show_format", "-of", "json", str(target)]))
    return {"source": path.name, "file": target.name, "seconds": float(probe["format"]["duration"]),
            "sha256": hashlib.sha256(target.read_bytes()).hexdigest()}

with ThreadPoolExecutor(max_workers=3) as workers:
    records = list(workers.map(convert, enumerate(files, 1)))
catalog = "extends RefCounted\n## User-supplied ArcadaMusic; generated by tools/prepare_music.py.\nconst STREAMS := [\n"
catalog += "".join(f'\tpreload("res://assets/music/{r["file"]}"),\n' for r in records) + "]\n"
(DEST / "catalog.gd").write_text(catalog, encoding="utf-8")
(DEST / "sources.json").write_text(json.dumps({"source_folder": str(SOURCE), "processing": "stereo 44.1 kHz Vorbis q4, loudnorm -18 LUFS / -2 dBTP", "tracks": records}, ensure_ascii=False, indent=2), encoding="utf-8")
(DEST / "SOURCES.txt").write_text("Music supplied by the user from C:/Users/dmitr/Downloads/ArcadaMusic on 2026-11-03.\nOriginal filenames (Ronaldoreyz), converted files and hashes: sources.json.\nNo external music was downloaded by the agent.\n", encoding="utf-8")
print(f"Prepared {len(records)} OGG tracks, {sum(r['seconds'] for r in records):.1f} seconds")
